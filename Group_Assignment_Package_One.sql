--Establish inventory quantities before purchase

SELECT B.BOOK_ID,
    B.BOOKS_NAME AS BOOK_TITLE,
    I.INVENTORY_BOOK_QUANTITY AS QUANTITY_BEFORE_PURCHASE
FROM INVENTORY I
JOIN BOOKS B
    ON I.INVENTORY_BOOK_ID = B.BOOK_ID
WHERE B.BOOK_ID IN (1, 3, 5)
ORDER BY B.BOOK_ID;

--Verify audit log is empty before processing a purchase

SELECT COUNT(*) AS AUDIT_RECORDS_BEFORE_PURCHASE
FROM AUDIT_LOG;

--Establish record counts before processing a purchase

SELECT
    (SELECT COUNT(*) FROM CUSTOMER_PURCHASE) AS PURCHASE_COUNT,
    (SELECT COUNT(*) FROM ORDERED_BOOKS) AS ORDERED_BOOKS_COUNT
FROM DUAL;


--Making a purchase
SET SERVEROUTPUT ON;

DECLARE
    V_PURCHASE_ID CUSTOMER_PURCHASE.CUSTOMER_PURCHASE_ID%TYPE;
    V_TOTAL_COST NUMBER;

BEGIN
    --Create purchase for customer 3
    PURCHASE_PACKAGE.PURCHASE_BOOKS(3, V_PURCHASE_ID);

    --Add books
    PURCHASE_PACKAGE.ADD_ORDERED_BOOKS(V_PURCHASE_ID, 1, 2);
    PURCHASE_PACKAGE.ADD_ORDERED_BOOKS(V_PURCHASE_ID, 3, 3);
    PURCHASE_PACKAGE.ADD_ORDERED_BOOKS(V_PURCHASE_ID, 5, 1);

    --Process Sale
    PURCHASE_PACKAGE.PROCESS_PURCHASE(V_PURCHASE_ID);

    --Calculate total cost
    V_TOTAL_COST :=
        PURCHASE_PACKAGE.CALCULATE_PURCHASE_COST(V_PURCHASE_ID);

    --Display results
    DBMS_OUTPUT.PUT_LINE('Purchase ID: ' || V_PURCHASE_ID);
    DBMS_OUTPUT.PUT_LINE('Total Purchase Cost: $' || V_TOTAL_COST);

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
