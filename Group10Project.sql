DROP Table BOOKS CASCADE CONSTRAINTS;
DROP Table PUBLISHER CASCADE CONSTRAINTS;
DROP Table AUTHOR CASCADE CONSTRAINTS;
DROP Table CUSTOMER CASCADE CONSTRAINTS;
DROP Table CUSTOMER_PURCHASE CASCADE CONSTRAINTS; 
DROP Table CUSTOMER_RETURN CASCADE CONSTRAINTS;
DROP Table ORDERED_BOOKS CASCADE CONSTRAINTS;
DROP Table INVENTORY CASCADE CONSTRAINTS;
DROP Table INVENTORY_ORDERED_BOOKS CASCADE CONSTRAINTS;

--TABLES

CREATE TABLE BOOKS (
    BOOK_ID NUMBER(10,0),
    BOOKS_NAME VARCHAR2(50),
    BOOKS_AUTHOR_ID VARCHAR2(50),
    BOOKS_PUBLISHER_ID VARCHAR2(50),
    BOOKS_ISBN VARCHAR2(13),
    BOOKS_PUBLISHER_DATE DATE,
    BOOKS_DESCRIPTION VARCHAR2(500),
    BOOKS_PRICE NUMBER(10,2)
);

CREATE TABLE PUBLISHER(
    PUBLISHER_ID NUMBER(6,0),
    PUBLISHER_NAME VARCHAR2(50)
);

CREATE TABLE AUTHOR(
    AUTHER_ID NUMBER(10,0),
    AUTHOR_NAME VARCHAR2(50)
);

CREATE TABLE CUSTOMER(
    CUSTOMER_ID NUMBER(10,0),
    CUSTOMER_NAME VARCHAR2(50),
    CUSTOMER_PHONE VARCHAR2(50),
    CUSTOMER_EMAIL VARCHAR2(100),
    CUSTOMER_CITY VARCHAR2(50),
    CUSTOMER_PROVINCE VARCHAR2(50),
    CUSTOMER_POSTAL_CODE VARCHAR2(7)
    
);
--This table acts as a general order for a single purchase.
--The specific items in the purchase would be referenced
--From the ORDER_ITEMS table
CREATE TABLE CUSTOMER_PURCHASE(
    CUSTOMER_PURCHASE_ID NUMBER(10,0),
    CUSTOMER_ID NUMBER(10,0),
    CUSTOMER_ORDER_DATE DATE
);

CREATE TABLE CUSTOMER_RETURN(
    CUSTOMER_RETURN_ID NUMBER(10,0),
    ORDERED_BOOKS_ID NUMBER(10,0),
    RETURNED_BOOKS_QUANTITY NUMBER(10,0),
    CUSTOMER_ID NUMBER(10,0),
    CUSTOMER_RETURN_DATE DATE
); 

--Order Items table should contain the actual books ordered or returned
CREATE TABLE ORDERED_BOOKS(
    ORDERED_BOOKS_ID NUMBER(10,0),
    CUSTOMER_PURCHASE_ID NUMBER(10,0),
    ORDERED_BOOK_ID NUMBER(10,0),
    ORDERED_BOOKS_QUANTITY NUMBER(5,0),
    ORDERED_BOOKS_PRICE NUMBER(10,2)
);

CREATE TABLE INVENTORY(
    INVENTORY_ID NUMBER(10,0),
    INVENTORY_BOOK_ID NUMBER(10,0),
    INVENTORY_BOOK_QUANTITY NUMBER(10,0)
);

CREATE TABLE INVENTORY_ORDERED_BOOKS (
    INVENTORY_ORDERED_ID NUMBER(10,0),
    INVENTORY_ORDERED_BOOK_ID NUMBER(10,0),
    INVENTORY_ORDER_DATE DATE,
    INVENTORY_ORDERED_QUANTITY NUMBER(10,0)
);


    

