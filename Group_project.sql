--TABLES

CREATE TABLE CATEGORY(
    CATEGORY_ID NUMBER(10,0),
    CATEGORY_NAME VARCHAR2(50) NOT NULL,

    CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT U_CATEGORY_NAME UNIQUE (CATEGORY_NAME)
);

CREATE TABLE PUBLISHER(
    PUBLISHER_ID NUMBER(10,0),
    PUBLISHER_NAME VARCHAR2(50) CONSTRAINT NN_PUBLISHER_NAME NOT NULL,
    
    CONSTRAINT PK_PUBLISHER_ID PRIMARY KEY (PUBLISHER_ID)
);

CREATE TABLE AUTHOR(
    AUTHOR_ID NUMBER(10,0),
    AUTHOR_NAME VARCHAR2(50) CONSTRAINT NN_AUTHOR_NAME NOT NULL,
    
    CONSTRAINT PK_AUTHOR PRIMARY KEY (AUTHOR_ID)
);

CREATE TABLE BOOKS (
    BOOK_ID NUMBER(10,0),
    BOOKS_NAME VARCHAR2(150) NOT NULL,
    BOOKS_CATEGORY_ID NUMBER(10,0) NOT NULL,
    BOOKS_AUTHOR_ID NUMBER(10,0) NOT NULL,
    BOOKS_PUBLISHER_ID NUMBER(10,0) NOT NULL,
    BOOKS_ISBN VARCHAR2(13) NOT NULL,
    BOOKS_PUBLICATION_DATE DATE,
    BOOKS_DESCRIPTION VARCHAR2(2000),
    BOOKS_PRICE NUMBER(10,2) NOT NULL,
    BOOKS_EMBEDDING VECTOR(384, FLOAT32),
    
    CONSTRAINT PK_BOOKS PRIMARY KEY (BOOK_ID),
    CONSTRAINT UNIQUE_BOOKS_ISBN UNIQUE (BOOKS_ISBN),
    CONSTRAINT CHECK_BOOKS_PRICE CHECK (BOOKS_PRICE >= 0),
    
    --Foreign Key 1 = Author ID from the AUTHOR Table
    CONSTRAINT FK_BOOKS_AUTHOR FOREIGN KEY (BOOKS_AUTHOR_ID)
        REFERENCES AUTHOR(AUTHOR_ID),
    --Foreign Key 2 = Category ID from the CATEGORY Table
    CONSTRAINT FK_BOOKS_CATEGORY FOREIGN KEY (BOOKS_CATEGORY_ID)
        REFERENCES CATEGORY(CATEGORY_ID),
    --Foreign Key 3 = Publisher ID from the Publisher Table
    CONSTRAINT FK_BOOKS_PUBLISHER FOREIGN KEY (BOOKS_PUBLISHER_ID)
        REFERENCES PUBLISHER(PUBLISHER_ID)
);


