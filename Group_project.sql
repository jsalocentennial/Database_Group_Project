--Trigger Two - updates order status in audit log
CREATE OR REPLACE TRIGGER TRG_AUDIT_ORDER_STATUS
AFTER UPDATE OF ORDER_STATUS ON CUSTOMER_PURCHASE
FOR EACH ROW
BEGIN
    IF :OLD.ORDER_STATUS != :NEW.ORDER_STATUS THEN
        INSERT INTO AUDIT_LOG (TABLE_NAME, RECORD_ID, COLUMN_NAME, ACTION_TYPE, OLD_VALUE, NEW_VALUE)
        VALUES ('CUSTOMER_PURCHASE', :NEW.CUSTOMER_PURCHASE_ID, 'ORDER_STATUS', 'UPDATE', :OLD.ORDER_STATUS, :NEW.ORDER_STATUS);
    END IF;
END;
/

--Trigger Three - Validate order status change

CREATE OR REPLACE TRIGGER TRG_VALIDATE_PURCHASE_STATUS
BEFORE UPDATE OF ORDER_STATUS ON CUSTOMER_PURCHASE
FOR EACH ROW
BEGIN
    IF :OLD.ORDER_STATUS != :NEW.ORDER_STATUS THEN
        IF :OLD.ORDER_STATUS = 'PENDING' THEN
            IF :NEW.ORDER_STATUS NOT IN ('PROCESSING', 'CANCELLED') THEN
                RAISE_APPLICATION_ERROR(-20011,
                    'Invalid status transition from PENDING.');
            END IF;
        ELSIF :OLD.ORDER_STATUS = 'PROCESSING' THEN
            IF :NEW.ORDER_STATUS != 'SHIPPED' THEN
                RAISE_APPLICATION_ERROR(-20012,
                    'Invalid status transition from PROCESSING.');
            END IF;
        ELSIF :OLD.ORDER_STATUS = 'SHIPPED' THEN
            IF :NEW.ORDER_STATUS != 'COMPLETED' THEN
                RAISE_APPLICATION_ERROR(-20013,
                    'Invalid status transition from SHIPPED.');
            END IF;
        ELSIF :OLD.ORDER_STATUS IN ('COMPLETED', 'CANCELLED') THEN
            RAISE_APPLICATION_ERROR(-20014,
                'Completed or cancelled orders cannot change status.');
        END IF;
    END IF;
END;
