CREATE TABLE CUSTOMER(
    CUSTOMER_ID NUMBER(10,0),
    CUSTOMER_NAME VARCHAR2(50) CONSTRAINT NN_CUSTOMER_NAME NOT NULL,
    CUSTOMER_PHONE VARCHAR2(50),
    CUSTOMER_EMAIL VARCHAR2(100) CONSTRAINT NN_CUSTOMER_EMAIL NOT NULL,
    CUSTOMER_CITY VARCHAR2(50),
    CUSTOMER_PROVINCE VARCHAR2(50),
    CUSTOMER_POSTAL_CODE VARCHAR2(7),
    
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT U_CUSTOMER_EMAIL UNIQUE (CUSTOMER_EMAIL),
    CONSTRAINT CHECK_CUSTOMER_EMAIL CHECK (CUSTOMER_EMAIL LIKE '%@%.%') -- Check for email format (something@something.something)
);

--This table acts as a general order for a single purchase.
--The specific items in the purchase would be referenced
--from the ORDERED_BOOKS table
CREATE TABLE CUSTOMER_PURCHASE(
    CUSTOMER_PURCHASE_ID NUMBER(10,0),
    CUSTOMER_ID NUMBER(10,0) NOT NULL,
    CUSTOMER_ORDER_DATE DATE DEFAULT SYSDATE NOT NULL,
    ORDER_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    
    CONSTRAINT PK_CUSTOMER_PURCHASE PRIMARY KEY (CUSTOMER_PURCHASE_ID),
    
    --Foreign Key = Customer ID from CUSTOMER Table
    CONSTRAINT FK_PURCHASE_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),
        
    --Makes sure order status is from predefined option
    CONSTRAINT CK_PURCHASE_STATUS
        CHECK (ORDER_STATUS IN (
            'PENDING',              -- INVENTORY NOT UPDATED
            'PROCESSING',           -- INVENTORY UPDATED
            'SHIPPED',
            'COMPLETED',
            'CANCELLED'
        ))
);

--Ordered Books table should contain the actual books ordered
CREATE TABLE ORDERED_BOOKS(
    ORDERED_BOOKS_ID NUMBER(10,0),
    CUSTOMER_PURCHASE_ID NUMBER(10,0) NOT NULL,         --Purchase id related to order
    ORDERED_BOOK_ID NUMBER(10,0) NOT NULL,
    ORDERED_BOOKS_QUANTITY NUMBER(5,0) NOT NULL,
    ORDERED_BOOKS_PRICE NUMBER(10,2) NOT NULL,
    
    CONSTRAINT PK_ORDERED_BOOKS PRIMARY KEY (ORDERED_BOOKS_ID),
    
    --Foreign Key 1 = The PURCHASE_ID from the CUSTOMER_PURCHASE Table
    CONSTRAINT FK_ORDERED_PURCHASE FOREIGN KEY (CUSTOMER_PURCHASE_ID)
        REFERENCES CUSTOMER_PURCHASE(CUSTOMER_PURCHASE_ID),
    --Foreign Key 2 = The book ID from the BOOKS Table
    CONSTRAINT FK_ORDERED_BOOK FOREIGN KEY (ORDERED_BOOK_ID)
        REFERENCES BOOKS(BOOK_ID),
    --Quantity above 0 check
    CONSTRAINT CK_ORDERED_QUANTITY
        CHECK (ORDERED_BOOKS_QUANTITY > 0),
    --Price above 0 check
    CONSTRAINT CK_ORDERED_PRICE
        CHECK (ORDERED_BOOKS_PRICE >=0),
    --Book ID only appears once per order
    CONSTRAINT U_ORDERED_BOOK
        UNIQUE (CUSTOMER_PURCHASE_ID, ORDERED_BOOK_ID)
);

CREATE TABLE CUSTOMER_RETURN(
    CUSTOMER_RETURN_ID NUMBER(10,0),
    ORDERED_BOOKS_ID NUMBER(10,0) NOT NULL,
    CUSTOMER_RETURN_DATE DATE NOT NULL,
    RETURN_QUANTITY NUMBER(10,0) NOT NULL,
    
    CONSTRAINT PK_CUSTOMER_RETURN PRIMARY KEY (CUSTOMER_RETURN_ID),
    
    --Foreign Key = Book_ID from the Book table
    CONSTRAINT FK_RETURN_ORDERED_BOOK FOREIGN KEY (ORDERED_BOOKS_ID)
        REFERENCES ORDERED_BOOKS(ORDERED_BOOKS_ID),
    --Quantity check greater than 0
    CONSTRAINT CK_RETURN_QUANTITY
        CHECK (RETURN_QUANTITY > 0)
); 

--Store inventory
CREATE TABLE INVENTORY(
    INVENTORY_ID NUMBER(10,0),
    INVENTORY_BOOK_ID NUMBER(10,0) NOT NULL,
    INVENTORY_BOOK_QUANTITY NUMBER(10,0) NOT NULL,
    
    CONSTRAINT PK_INVENTORY PRIMARY KEY (INVENTORY_ID),
    
    --Foreigh Key = Book_ID of the book from the BOOKS Table
    CONSTRAINT FK_INVENTORY_BOOK FOREIGN KEY (INVENTORY_BOOK_ID)
        REFERENCES BOOKS(BOOK_ID),
        
    --Book Id is unique so multiple copies of same book cannot be added to inventory
    CONSTRAINT U_INVENTORY_BOOK
        UNIQUE (INVENTORY_BOOK_ID),
    
    --Must have 0 or greater copies of book in inventory
    CONSTRAINT CK_INVENTORY_QUANTITY
        CHECK (INVENTORY_BOOK_QUANTITY >= 0)
);

--Orders for the store inventory
CREATE TABLE INVENTORY_ORDERED_BOOKS (
    INVENTORY_ORDERED_ID NUMBER(10,0),
    INVENTORY_ORDERED_BOOK_ID NUMBER(10,0) NOT NULL,
    INVENTORY_ORDER_DATE DATE NOT NULL,
    INVENTORY_ORDERED_QUANTITY NUMBER(10,0) NOT NULL,
    INVENTORY_ORDER_STATUS VARCHAR2(20)
    DEFAULT 'ORDERED' NOT NULL,
    
    CONSTRAINT PK_INVENTORY_ORDERED PRIMARY KEY (INVENTORY_ORDERED_ID),
    
    --Foreign Key = The book_ID of the ordered books from the BOOKS Table
    CONSTRAINT FK_INVENTORY_ORDER_BOOK FOREIGN KEY (INVENTORY_ORDERED_BOOK_ID)
        REFERENCES BOOKS(BOOK_ID),
    
    --Order should be for more than 0 copies
    CONSTRAINT CK_INVENTORY_ORDER_QUANTITY
        CHECK (INVENTORY_ORDERED_QUANTITY > 0),
        
    --Order status
    CONSTRAINT CK_INVENTORY_ORDER_STATUS
    CHECK (INVENTORY_ORDER_STATUS IN (
        'ORDERED',
        'RECEIVED',
        'CANCELLED'
    ))
);

    --Sequence for audit log
CREATE SEQUENCE AUDIT_LOG_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;


    --Audit Log
CREATE TABLE AUDIT_LOG (
    AUDIT_ID NUMBER(10,0) DEFAULT AUDIT_LOG_SEQ.NEXTVAL,                    
    TABLE_NAME VARCHAR2(50) NOT NULL,                --Table being audited
    COLUMN_NAME VARCHAR2(50) NOT NULL,               --Column being audited
    ACTION_TYPE VARCHAR2(10) NOT NULL,               --Insert or update
    RECORD_ID NUMBER(10,0) NOT NULL,                 --ID of the record being audited
    NEW_VALUE VARCHAR2(500),
    AUDIT_DATE DATE DEFAULT SYSDATE NOT NULL,
    
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (AUDIT_ID),
    
    CONSTRAINT CK_AUDIT_ACTION
        CHECK (ACTION_TYPE IN (
            'INSERT',
            'UPDATE',
            'DELETE'
        ))
);   


--Customer Reviews
CREATE TABLE BOOK_REVIEW (
    REVIEW_ID NUMBER(10,0),
    BOOK_ID NUMBER(10,0) NOT NULL,                    --Book being reviewed
    CUSTOMER_ID NUMBER(10,0) NOT NULL,                --Customer who wrote the review
    REVIEW_TEXT VARCHAR2(2000) NOT NULL,              --Review text
    REVIEW_RATING NUMBER(1,0) NOT NULL,               --Rating from 1 to 5
    REVIEW_DATE DATE DEFAULT SYSDATE NOT NULL,
    REVIEW_EMBEDDING VECTOR(384, FLOAT32), 

    CONSTRAINT PK_BOOK_REVIEW PRIMARY KEY (REVIEW_ID),

    --Foreign Key = Book_ID from the Book table
    CONSTRAINT FK_REVIEW_BOOK FOREIGN KEY (BOOK_ID)
        REFERENCES BOOKS(BOOK_ID),

    --Foreign Key = Customer_ID from the Customer table
    CONSTRAINT FK_REVIEW_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    --Rating must be between 1 and 5
    CONSTRAINT CK_REVIEW_RATING
        CHECK (REVIEW_RATING BETWEEN 1 AND 5)
);

