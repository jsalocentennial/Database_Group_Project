CREATE OR REPLACE PACKAGE BODY PURCHASE_PACKAGE IS

    --Procedure One - create the purchase and return the purchase ID
    PROCEDURE PURCHASE_BOOKS(
        P_CUSTOMER_ID IN CUSTOMER.CUSTOMER_ID%TYPE,
        P_CUSTOMER_PURCHASE_ID OUT CUSTOMER_PURCHASE.CUSTOMER_PURCHASE_ID%TYPE
    )
    IS
        V_CUSTOMER_ID CUSTOMER.CUSTOMER_ID%TYPE;
    BEGIN
        SELECT CUSTOMER_ID
        INTO V_CUSTOMER_ID
        FROM CUSTOMER
        WHERE P_CUSTOMER_ID = CUSTOMER_ID;
    INSERT INTO CUSTOMER_PURCHASE (
        CUSTOMER_PURCHASE_ID,
        CUSTOMER_ID,
        CUSTOMER_ORDER_DATE,
        ORDER_STATUS
    )
    VALUES (
        CUSTOMER_PURCHASE_SEQ.NEXTVAL,
        V_CUSTOMER_ID,
        SYSDATE,
        'PENDING'
    )
    RETURNING CUSTOMER_PURCHASE_ID INTO P_CUSTOMER_PURCHASE_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20001, 'Customer ID not found.');
    END PURCHASE_BOOKS;


    --Procedure Two - Add the books to the purchase
    PROCEDURE ADD_ORDERED_BOOKS(
        P_CUSTOMER_PURCHASE_ID IN CUSTOMER_PURCHASE.CUSTOMER_PURCHASE_ID%TYPE,
        P_ORDERED_BOOK_ID IN BOOKS.BOOK_ID%TYPE,
        P_ORDERED_BOOKS_QUANTITY IN ORDERED_BOOKS.ORDERED_BOOKS_QUANTITY%TYPE
    )
    IS
        V_ORDER_STATUS CUSTOMER_PURCHASE.ORDER_STATUS%TYPE;
        V_BOOK_PRICE BOOKS.BOOKS_PRICE%TYPE;
    BEGIN   
        --Get order status and confirm pending                                          
        SELECT ORDER_STATUS
        INTO V_ORDER_STATUS
        FROM CUSTOMER_PURCHASE
        WHERE P_CUSTOMER_PURCHASE_ID = CUSTOMER_PURCHASE_ID;
        IF V_ORDER_STATUS != 'PENDING' THEN
            RAISE_APPLICATION_ERROR(-20002, 'Order status not pending');
        END IF;
        --Get book Price
        SELECT BOOKS_PRICE
        INTO V_BOOK_PRICE
        FROM BOOKS
        WHERE P_ORDERED_BOOK_ID = BOOK_ID;
        IF P_ORDERED_BOOKS_QUANTITY <= 0 OR P_ORDERED_BOOKS_QUANTITY IS NULL THEN
            RAISE_APPLICATION_ERROR(-20003, 'Quantity must be greater than 0');
        END IF;
        --Insert into Ordered_books
        INSERT INTO ORDERED_BOOKS (
            ORDERED_BOOKS_ID,
            CUSTOMER_PURCHASE_ID,
            ORDERED_BOOK_ID,
            ORDERED_BOOKS_QUANTITY,
            ORDERED_BOOKS_PRICE
        ) 
        VALUES (
            ORDERED_BOOKS_SEQ.NEXTVAL,
            P_CUSTOMER_PURCHASE_ID,
            P_ORDERED_BOOK_ID,
            P_ORDERED_BOOKS_QUANTITY,
            V_BOOK_PRICE
        );
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20004, 'Purchase or Book ID not found');
            WHEN DUP_VAL_ON_INDEX THEN
                RAISE_APPLICATION_ERROR(-20005, 'Same book already included in purchase.');
    END ADD_ORDERED_BOOKS;

    --Procedure Three With Curser - Check inventory, deduct stock, update purchase status
    PROCEDURE PROCESS_PURCHASE(
        P_CUSTOMER_PURCHASE_ID IN CUSTOMER_PURCHASE.CUSTOMER_PURCHASE_ID%TYPE
    )
    IS
        V_ORDER_STATUS CUSTOMER_PURCHASE.ORDER_STATUS%TYPE;
        V_INVENTORY_QUANTITY INVENTORY.INVENTORY_BOOK_QUANTITY%TYPE;
        V_BOOK_COUNT NUMBER := 0;
    --Declare curser
    CURSOR C_ORDERED_BOOKS IS
        SELECT ORDERED_BOOK_ID, ORDERED_BOOKS_QUANTITY
        FROM ORDERED_BOOKS
        WHERE CUSTOMER_PURCHASE_ID = P_CUSTOMER_PURCHASE_ID;
    V_ORDERED_BOOK C_ORDERED_BOOKS%ROWTYPE;
    BEGIN
        SELECT ORDER_STATUS
        INTO V_ORDER_STATUS
        FROM CUSTOMER_PURCHASE
        WHERE CUSTOMER_PURCHASE_ID = P_CUSTOMER_PURCHASE_ID
        FOR UPDATE;
        IF V_ORDER_STATUS != 'PENDING' THEN
            RAISE_APPLICATION_ERROR(-20006, 'Order status not pending');
        END IF;
    --Open curser and loop through ordered books to check inventory
    OPEN C_ORDERED_BOOKS;
    LOOP
        FETCH C_ORDERED_BOOKS INTO V_ORDERED_BOOK;
        EXIT WHEN C_ORDERED_BOOKS%NOTFOUND;
        SELECT INVENTORY_BOOK_QUANTITY
        INTO V_INVENTORY_QUANTITY
        FROM INVENTORY
        WHERE INVENTORY_BOOK_ID = V_ORDERED_BOOK.ORDERED_BOOK_ID
        FOR UPDATE;
        IF V_INVENTORY_QUANTITY < V_ORDERED_BOOK.ORDERED_BOOKS_QUANTITY THEN
            RAISE_APPLICATION_ERROR(-20007, 'Insufficient stock for book ID: ' || V_ORDERED_BOOK.ORDERED_BOOK_ID);
        END IF;
        V_BOOK_COUNT := V_BOOK_COUNT + 1;
    END LOOP;
    CLOSE C_ORDERED_BOOKS;
    IF V_BOOK_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20008, 'No books found for this purchase.');
    END IF;
    --User curser to loop through ordered books and deduct stock
    OPEN C_ORDERED_BOOKS;
    LOOP
        FETCH C_ORDERED_BOOKS INTO V_ORDERED_BOOK;
        EXIT WHEN C_ORDERED_BOOKS%NOTFOUND;
        UPDATE INVENTORY
        SET INVENTORY_BOOK_QUANTITY = INVENTORY_BOOK_QUANTITY - V_ORDERED_BOOK.ORDERED_BOOKS_QUANTITY
        WHERE INVENTORY_BOOK_ID = V_ORDERED_BOOK.ORDERED_BOOK_ID;
    END LOOP;
    CLOSE C_ORDERED_BOOKS;
    --Update order status to processed
    UPDATE CUSTOMER_PURCHASE
    SET ORDER_STATUS = 'PROCESSING'
    WHERE CUSTOMER_PURCHASE_ID = P_CUSTOMER_PURCHASE_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20009, 'Purchase OR inventory record not found.');
    END PROCESS_PURCHASE;

    --Function One - Calctulate cost of purchase
    FUNCTION CALCULATE_PURCHASE_COST(
        P_CUSTOMER_PURCHASE_ID IN CUSTOMER_PURCHASE.CUSTOMER_PURCHASE_ID%TYPE
    ) RETURN NUMBER
    IS
        V_TOTAL_COST NUMBER := 0;
        V_PURCHASE_ID CUSTOMER_PURCHASE.CUSTOMER_PURCHASE_ID%TYPE;
    BEGIN
        SELECT CUSTOMER_PURCHASE_ID
        INTO V_PURCHASE_ID
        FROM CUSTOMER_PURCHASE
        WHERE P_CUSTOMER_PURCHASE_ID = CUSTOMER_PURCHASE_ID;
        
        SELECT NVL(SUM(ORDERED_BOOKS_QUANTITY * ORDERED_BOOKS_PRICE), 0)
        INTO V_TOTAL_COST
        FROM ORDERED_BOOKS
        WHERE CUSTOMER_PURCHASE_ID = P_CUSTOMER_PURCHASE_ID;
        RETURN V_TOTAL_COST;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20010, 'Purchase record not found.');
    END CALCULATE_PURCHASE_COST;

END PURCHASE_PACKAGE;
